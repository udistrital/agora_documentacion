INSERT INTO terceros.tipo_documento
    (nombre, descripcion, codigo_abreviacion, activo, fecha_creacion, fecha_modificacion)
SELECT
    datos.nombre,
    datos.descripcion,
    datos.codigo,
    TRUE,
    LOCALTIMESTAMP,
    LOCALTIMESTAMP
FROM (
    VALUES
        ('REGISTRO CIVIL DE NACIMIENTO', 'REGISTRO CIVIL DE NACIMIENTO', 'RC'),
        ('TARJETA DE IDENTIDAD', 'TARJETA DE IDENTIDAD', 'TI'),
        ('CÉDULA DE CIUDADANÍA', 'CÉDULA DE CIUDADANÍA', 'CC'),
        ('CERTIFICADO REGISTRADURÍA SIN IDENTIFICACIÓN', 'CERTIFICADO REGISTRADURÍA SIN IDENTIFICACIÓN', 'CRSI'),
        ('TARJETA DE EXTRANJERÍA', 'TARJETA DE EXTRANJERÍA', 'TE'),
        ('CÉDULA DE EXTRANJERÍA', 'CÉDULA DE EXTRANJERÍA', 'CE'),
        ('NIT', 'NIT', 'NIT'),
        ('IDENTIFICACIÓN DE EXTRANJEROS DIFERENTE AL NIT ASIGNADO DIAN', 'IDENTIFICACIÓN DE EXTRANJEROS DIFERENTE AL NIT ASIGNADO DIAN', 'IEDD'),
        ('PASAPORTE', 'PASAPORTE', 'PAS'),
        ('DOCUMENTO DE IDENTIFICACIÓN EXTRANJERO', 'DOCUMENTO DE IDENTIFICACIÓN EXTRANJERO', 'DIE'),
        ('SIN IDENTIFICACIÓN DEL EXTERIOR O PARA USO DEFINIDO POR DIAN', 'SIN IDENTIFICACIÓN DEL EXTERIOR O PARA USO DEFINIDO POR DIAN', 'SIED'),
        ('DOCUMENTO DE IDENTIFICACIÓN EXTRANJERO PERSONA JURÍDICA', 'DOCUMENTO DE IDENTIFICACIÓN EXTRANJERO PERSONA JURÍDICA', 'DIEPJ'),
        ('CARNÉ DIPLOMÁTICO', 'CARNÉ DIPLOMÁTICO', 'CD')
) AS datos(nombre, descripcion, codigo)
WHERE NOT EXISTS (
    SELECT 1
    FROM terceros.tipo_documento existente
    WHERE existente.codigo_abreviacion = datos.codigo
);
